import { projectSection } from './ui-navigation';
import { test, expect, type Page } from '@playwright/test';
import { projectInput } from '../support/project-fixture';
import { workItemDefaults } from '../../shared/work-items';
import { dayIndex, dateAt, periods, newWeekConvention } from '../../shared/plans';

async function login(page: Page, role: string) {
  await page.goto('/masuk');
  await page.getByLabel('Email', { exact: true }).fill(`${role}@example.test`);
  await page.getByLabel('Kata sandi', { exact: true }).fill(process.env.SIMP_TEST_PASSWORD!);
  await page.getByRole('button', { name: 'Masuk', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Proyek Anda' })).toBeVisible();
}
test('pemeriksaan target memilih pekerjaan yang belum 100 persen', async ({ page }, info) => {
  await login(page, 'team_leader');
  const me = await (await page.request.get('/api/auth/me')).json();
  const start = new Date().toISOString().slice(0,10), end = dateAt(dayIndex(start) + 13);
  const headers = { origin: 'http://127.0.0.1:5174' };
  const response = await page.request.post('/api/projects', { headers, data: projectInput({ projectCode: `TARGET-${info.project.name}-${Date.now()}`, teamLeaderId: me.user.id, startDate: start, endDate: end }) });
  expect(response.status()).toBe(201);
  const project = (await response.json()).project;
  for (const [code, name] of [['I.1', 'Papan Nama Proyek'], ['IV.A.8', 'Pengelasan']]) {
    const created = await page.request.post(`/api/projects/${project.id}/work-items`, { headers, data: { ...workItemDefaults, code, name, unit: 'm', contractVolume: '1', unitPrice: '100' } });
    expect(created.status()).toBe(201);
  }
  await page.goto(`/proyek/${project.id}/rencana`);
  await page.getByRole('button', { name: 'Buat Rencana Awal' }).click();
  await page.getByRole('button', { name: 'Lanjut ke Target' }).click();
  await page.getByLabel('Pekerjaan yang diatur').selectOption({ label: 'I.1 · Papan Nama Proyek' });
  await page.getByLabel(/Minggu 1/).fill('100');
  await page.getByRole('button', { name: 'Periksa Rencana' }).click();
  await expect(page.getByRole('alert')).toContainText('IV.A.8 · Pengelasan');
  await expect(page.locator('#plan-item option:checked')).toHaveText('IV.A.8 · Pengelasan');
  await expect(page.locator('#plan-item')).toBeFocused();
  await expect(page.locator('.target-total')).toContainText('0,00%');
  await page.getByLabel(/Minggu 2/).fill('100');
  await page.getByRole('button', { name: 'Periksa Rencana' }).click();
  await expect(page.getByText('Langkah 3 dari 3')).toBeVisible();
});
