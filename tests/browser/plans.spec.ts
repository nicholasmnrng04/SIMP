test('Owner membaca rencana, tidak dapat menerbitkan dan dapat memulihkan kegagalan koneksi', async ({ page }, info) => {
  await login(page, 'owner'); await page.goto('/proyek');
  await page.getByRole('link', { name: 'Proyek Penugasan Uji', exact: true }).click();
  await page.route('**/api/projects/*/plans', route => route.fulfill({ status: 503, contentType: 'application/json', body: JSON.stringify({ error: { message: 'Rencana belum dapat dimuat.' } }) }));
  await projectSection(page,'rencana');
  await expect(page.getByRole('alert')).toContainText('Rencana belum dapat dimuat.');
  await page.unroute('**/api/projects/*/plans');
  await page.getByRole('button', { name: 'Coba Lagi', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'V1 · Rencana Awal', exact: true })).toBeVisible();
  await expect(page.locator('.plan-period-table')).toContainText('100,00%');
  await expect(page.getByRole('button', { name: 'Buat Perubahan Rencana', exact: true })).toHaveCount(0);
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  await page.screenshot({ path: info.outputPath('owner-rencana.png'), fullPage: true });
});
